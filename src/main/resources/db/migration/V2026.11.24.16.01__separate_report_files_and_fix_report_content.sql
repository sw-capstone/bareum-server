-- 기존 접수 취소와 확인 가능한 접수 실패를 소프트 삭제 상태로 옮긴다.
UPDATE report r
SET deleted_at = COALESCE(r.intake_cancelled_at, (
    SELECT MIN(i.completed_at) FROM report_intake_request i
    WHERE i.report_id = r.id AND i.status = 'FAILED'
));

CREATE TABLE report_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES report(id),
    file_role VARCHAR(30) NOT NULL,
    file_format VARCHAR(30) NOT NULL,
    filename VARCHAR(255) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64),
    object_key TEXT NOT NULL,
    version_id TEXT,
    deleted_at TIMESTAMPTZ,
    cleanup_after TIMESTAMPTZ,
    s3_deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_report_file_role UNIQUE (report_id, file_role),
    CONSTRAINT uk_report_file_object_key UNIQUE (object_key),
    CONSTRAINT ck_report_file_role CHECK (
        file_role = 'ORIGINAL' OR (file_role = 'CONVERTED_PDF' AND file_format = 'PDF')
    ),
    CONSTRAINT ck_report_file_format CHECK (file_format IN ('PDF', 'DOCX', 'HWPX')),
    CONSTRAINT ck_report_file_size CHECK (size_bytes > 0),
    CONSTRAINT ck_report_file_sha256 CHECK (sha256 IS NULL OR sha256 ~ '^[a-f0-9]{64}$'),
    CONSTRAINT ck_report_file_deletion CHECK (
        (cleanup_after IS NULL OR (deleted_at IS NOT NULL AND cleanup_after >= deleted_at))
        AND (s3_deleted_at IS NULL OR deleted_at IS NOT NULL)
    )
);

INSERT INTO report_file (report_id, file_role, file_format, filename, size_bytes, sha256,
                         object_key, version_id, deleted_at, cleanup_after, s3_deleted_at, created_at, updated_at)
SELECT r.id, 'ORIGINAL', r.file_format, r.original_filename, r.file_size_bytes, r.source_sha256,
       r.source_object_key, r.source_version_id, COALESCE(r.deleted_at, r.source_deleted_at),
       CASE WHEN r.deleted_at IS NOT NULL AND r.source_deleted_at IS NULL
            THEN GREATEST(r.deleted_at, r.source_cleanup_after) END,
       r.source_deleted_at, r.created_at, r.updated_at
FROM report r
WHERE r.input_method = 'FILE' AND r.source_object_key IS NOT NULL;

CREATE INDEX idx_report_file_cleanup ON report_file (cleanup_after, id)
    WHERE s3_deleted_at IS NULL AND cleanup_after IS NOT NULL;

