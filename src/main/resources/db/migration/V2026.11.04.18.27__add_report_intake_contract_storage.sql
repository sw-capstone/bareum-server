ALTER TABLE report
    ADD COLUMN source_sha256 VARCHAR(64),
    ADD COLUMN source_version_id TEXT,
    ADD COLUMN intake_cancelled_at TIMESTAMPTZ,
    ADD COLUMN source_cleanup_after TIMESTAMPTZ,
    ADD CONSTRAINT ck_report_source_sha256
        CHECK (source_sha256 IS NULL OR source_sha256 ~ '^[a-f0-9]{64}$'),
    ADD CONSTRAINT ck_report_file_cleanup
        CHECK ((intake_cancelled_at IS NULL AND source_cleanup_after IS NULL) OR input_method = 'FILE');

ALTER TABLE report_parse_attempt ALTER COLUMN error_code TYPE VARCHAR(64);
ALTER TABLE report_parse_attempt ADD CONSTRAINT uk_report_parse_attempt_owner UNIQUE (report_id, id);
CREATE UNIQUE INDEX uk_report_parse_attempt_active ON report_parse_attempt (report_id)
    WHERE process_status IN ('PENDING', 'PROCESSING');

CREATE INDEX idx_report_source_cleanup ON report (source_cleanup_after, source_expires_at)
    WHERE input_method = 'FILE' AND source_deleted_at IS NULL;

CREATE TABLE report_intake_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member(id),
    request_key UUID NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    status VARCHAR(30) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    report_id BIGINT REFERENCES report(id),
    parse_attempt_id BIGINT,
    source_object_key TEXT,
    source_version_id TEXT,
    source_cleanup_after TIMESTAMPTZ,
    source_deleted_at TIMESTAMPTZ,
    response_status INTEGER,
    response_body JSONB,
    completed_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_report_intake_member_request_key UNIQUE (member_id, request_key),
    CONSTRAINT fk_report_intake_attempt FOREIGN KEY (report_id, parse_attempt_id)
        REFERENCES report_parse_attempt(report_id, id),
    CONSTRAINT ck_report_intake_attempt_pair CHECK ((report_id IS NULL) = (parse_attempt_id IS NULL)),
    CONSTRAINT ck_report_intake_fingerprint CHECK (request_fingerprint ~ '^[a-f0-9]{64}$'),
    CONSTRAINT ck_report_intake_status CHECK (status IN ('PROCESSING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_report_intake_completion CHECK (
        (status = 'PROCESSING' AND response_status IS NULL AND response_body IS NULL
            AND completed_at IS NULL AND expires_at IS NULL)
        OR
        (status IN ('SUCCEEDED', 'FAILED') AND response_status IS NOT NULL AND response_body IS NOT NULL
            AND jsonb_typeof(response_body) = 'object' AND completed_at IS NOT NULL AND expires_at IS NOT NULL
            AND completed_at >= requested_at AND expires_at >= completed_at + INTERVAL '24 hours'
            AND ((status = 'SUCCEEDED' AND response_status = 201 AND parse_attempt_id IS NOT NULL)
                OR (status = 'FAILED' AND response_status BETWEEN 400 AND 599)))
    ),
    CONSTRAINT ck_report_intake_orphan_cleanup CHECK (
        source_cleanup_after IS NULL
        OR (status = 'FAILED' AND report_id IS NULL AND source_object_key IS NOT NULL)
    ),
    CONSTRAINT ck_report_intake_orphan_deleted CHECK (
        source_deleted_at IS NULL OR (source_cleanup_after IS NOT NULL AND source_deleted_at >= source_cleanup_after)
    )
);

CREATE INDEX idx_report_intake_expiry ON report_intake_request (expires_at, id)
    WHERE status IN ('SUCCEEDED', 'FAILED');
CREATE INDEX idx_report_intake_orphan_cleanup ON report_intake_request (source_cleanup_after)
    WHERE report_id IS NULL AND source_object_key IS NOT NULL AND source_deleted_at IS NULL;
